@Injectable()
export class AuditEventListener implements OnModuleInit {
  private readonly logger = new Logger(AuditEventListener.name);

  constructor(
    private readonly eventBus: EventBusService,
    private readonly auditService: AuditService,
  ) {}

  onModuleInit(): void {
    for (const eventName of DOMAIN_AUDIT_EVENTS) {
      this.eventBus.subscribe(eventName, async (event: ApplicationEvent) => {
        await this.handleAuditEvent(event as AuditEvent);
      });
    }
  }

  /**
   * Handle incoming audit event from the EventBus and persist it via AuditService.
   */
  async handleAuditEvent(event: AuditEvent): Promise<void> {
    if (!event.organizationId) {
      // Skip events without tenant context
      return;
    }

    await this.auditService.record(event);
  }
}
